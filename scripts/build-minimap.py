"""
Builds src/data/minimap.ts: the interstates (I-285, I-75, I-85, I-20) drawn small, for the
little "where in Atlanta" map on each list card. Run rarely; the roads don't move.

    curl -A 'atl-minimap-build/1.0' https://overpass-api.de/api/interpreter --data-urlencode \
      'data=[out:json][timeout:120];way["highway"="motorway"]["ref"~"(^|;)I (285|75|85|20)(;|$)"](33.55,-84.62,34.0,-84.17);out geom;' -o hw.json
    python3 scripts/build-minimap.py hw.json

Road data © OpenStreetMap contributors (ODbL).
"""
import json, math, sys
d=json.load(open(sys.argv[1]))
LAT0=33.775; K=math.cos(math.radians(LAT0))
# Frame: the I-285 loop plus a margin.
pts285=[(p['lon'],p['lat']) for e in d['elements'] if e['tags']['ref']=='I 285' for p in e['geometry']]
minx=min(x for x,_ in pts285); maxx=max(x for x,_ in pts285); miny=min(y for _,y in pts285); maxy=max(y for _,y in pts285)
M=0.012
minx-=M/K; maxx+=M/K; miny-=M; maxy+=M
W=(maxx-minx)*K; H=(maxy-miny); S=100/max(W,H)
VW=round(W*S,1); VH=round(H*S,1)
def proj(lon,lat): return ((lon-minx)*K*S, (maxy-lat)*S)
def group(ref):
    if '285' in ref: return '285'
    if '75' in ref and '85' in ref: return 'conn'
    for r in ('75','85','20'):
        if 'I '+r in ref: return r
    return None
lines={}
for e in d['elements']:
    g=group(e['tags']['ref'])
    if g: lines.setdefault(g,[]).append([proj(p['lon'],p['lat']) for p in e['geometry']])
def chain(segs):
    segs=[s[:] for s in segs]; out=[]
    key=lambda p:(round(p[0],2),round(p[1],2))
    while segs:
        cur=segs.pop()
        grown=True
        while grown:
            grown=False
            for i,s in enumerate(segs):
                if key(s[0])==key(cur[-1]): cur+=s[1:]; segs.pop(i); grown=True; break
                if key(s[-1])==key(cur[0]): cur=s+cur[1:]; segs.pop(i); grown=True; break
        out.append(cur)
    return out
def dp(pts,tol):
    if len(pts)<3: return pts
    (x1,y1),(x2,y2)=pts[0],pts[-1]; dx,dy=x2-x1,y2-y1; L=math.hypot(dx,dy)
    dmax,idx=0,0
    for i in range(1,len(pts)-1):
        x,y=pts[i]; dd=abs(dy*x-dx*y+x2*y1-y2*x1)/L if L>1e-6 else math.hypot(x-x1,y-y1)
        if dd>dmax: dmax,idx=dd,i
    if dmax>tol: return dp(pts[:idx+1],tol)[:-1]+dp(pts[idx:],tol)
    return [pts[0],pts[-1]]
TOL=0.5
out={}
for g,segs in lines.items():
    paths=[]
    for c in chain(segs):
        s=dp(c,TOL)
        length=sum(math.hypot(s[i+1][0]-s[i][0],s[i+1][1]-s[i][1]) for i in range(len(s)-1))
        if length<1.5: continue
        paths.append('M'+' '.join(f'{x:.1f} {y:.1f}' for x,y in s))
    out[g]=' '.join(paths)
out['conn']=out.get('conn','')
ts = f"""// Generated by scripts/build-minimap.py from OpenStreetMap (© OpenStreetMap contributors, ODbL). Don't edit by hand.
// The interstates inside and around I-285, in a {VW} × {VH} box, for the list cards' little maps.

export const MINIMAP = {{
  width: {VW},
  height: {VH},
  /** The area drawn, to place a point on it (see miniMapPoint). */
  frame: {{ minLng: {minx:.5f}, maxLng: {maxx:.5f}, minLat: {miny:.5f}, maxLat: {maxy:.5f} }},
  /** The perimeter (I-285), then the roads through town. */
  loop: '{out['285']}',
  roads: '{' '.join(out[k] for k in ('75','85','conn','20') if out.get(k))}',
}};

/** Where a place sits on the little map, in its own units. */
export function miniMapPoint(lng: number, lat: number) {{
  const {{ frame, width, height }} = MINIMAP;
  const x = ((lng - frame.minLng) / (frame.maxLng - frame.minLng)) * width;
  const y = ((frame.maxLat - lat) / (frame.maxLat - frame.minLat)) * height;
  return {{ x: Math.round(x * 10) / 10, y: Math.round(y * 10) / 10 }};
}}
"""
open('src/data/minimap.ts', 'w').write(ts)
print(VW, VH)
